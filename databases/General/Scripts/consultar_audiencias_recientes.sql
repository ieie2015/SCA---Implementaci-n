

USE `mydb`;

SELECT
    a.NRO_AUDIENCIA AS `N° Audiencia`,
    a.idSOLICITUD_AGENDAMIENTO AS `ID Solicitud`,
    s.CUIJ AS `CUIJ`,
    s.CARATULA AS `Carátula`,
    a.idTIPO_AUDIENCIA AS `Tipo Audiencia`,
    ea.CODIGO AS `Estado`,
    a.DURACION_ESTIMADA AS `Duración (min)`
FROM `AUDIENCIA` a
JOIN `SOLICITUD_AGENDAMIENTO` s
  ON s.idSOLICITUD_AGENDAMIENTO = a.idSOLICITUD_AGENDAMIENTO
JOIN `ESTADO_AUDIENCIA` ea
  ON ea.idESTADO_AUDIENCIA = a.idESTADO_AUDIENCIA
ORDER BY a.FECHA_CREACION DESC, a.idAUDIENCIA DESC;

